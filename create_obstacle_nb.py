                "def tile_pbc_y(pts, Ly, r):\n",
                "    \"\"\"Custom Periodic Boundary Tiling for Y ONLY\"\"\"\n",
                "    y = pts[:, 1]\n",
                "    thresh_y = min(4.01 * r, Ly)\n",
                "    \n",
                "    pos_out = [pts]\n",
                "    if np.any(y <= thresh_y):\n",
                "        pts_u = pts[y <= thresh_y].copy()\n",
                "        pts_u[:, 1] += Ly\n",
                "        pos_out.append(pts_u)\n",
                "    if np.any(y >= (Ly - thresh_y)):\n",
                "        pts_d = pts[y >= (Ly - thresh_y)].copy()\n",
                "        pts_d[:, 1] -= Ly\n",
                "        pos_out.append(pts_d)\n",
                "        \n",
                "    return np.vstack(pos_out)"
